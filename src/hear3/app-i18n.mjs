const has=code=>HEAR3_LANGUAGE_CHOICES.includes(code);
export function resolveHear3Language({stored=null,browser='es'}={}){
 if(has(stored))return stored;
 if(typeof browser!=='string')return 'es';
 const normalized=browser.toLowerCase().split(/[-_]/)[0];
 return has(normalized)?normalized:'es';
}
export function translateHear3Ui(key,language='es'){
 return STRINGS[has(language)?language:'es'][key]??STRINGS.es[key]??null;
}
export function createHear3I18nController({doc,env=globalThis}={}){
 if(!doc)throw Error('Missing document for Hear language selector.');
 let storage=null,stored=null;
 // A privacy-restricted browser may throw merely when reading localStorage.
 try{storage=env.localStorage??null;stored=storage?.getItem(HEAR3_LANGUAGE_KEY);}catch{}
 let locale=resolveHear3Language({stored,browser:env.navigator?.language});
 const selector=doc.querySelector('[data-hear-language]');
 const note=doc.querySelector('[data-hear-language-note]');
 const apply=()=>{
  doc.documentElement.lang=locale==='zh'?'zh-Hans':locale;
  if(selector)selector.value=locale;
  for(const node of doc.querySelectorAll('[data-hear-i18n]')){
   const translated=translateHear3Ui(node.getAttribute('data-hear-i18n'),locale);
   if(translated!==null)node.textContent=translated;
  }
  if(note){
   note.hidden=locale==='es';
   note.textContent=translateHear3Ui('common.note',locale);
  }
  const Evt=doc.defaultView?.Event??env.Event;
  if(Evt)doc.defaultView?.dispatchEvent?.(new Evt('hear3:language-change'));
 };
 const change=(next)=>{
  if(!has(next))return false;
  locale=next;
  try{storage?.setItem(HEAR3_LANGUAGE_KEY,next);}catch{}
  apply();
  return true;
 };
 const onSelect=()=>change(selector.value);
 selector?.addEventListener('change',onSelect);
 const onStorage=event=>{
  if(event.key!==HEAR3_LANGUAGE_KEY)return;
  locale=resolveHear3Language({stored:event.newValue,browser:env.navigator?.language});
  apply();
 };
 env.addEventListener?.('storage',onStorage);
 apply();
 return Object.freeze({getLanguage:()=>locale,setLanguage:change,refresh:apply,
  dispose:()=>{selector?.removeEventListener('change',onSelect);
   env.removeEventListener?.('storage',onStorage);}});
}
if(typeof document!=='undefined'){
 const boot=()=>createHear3I18nController({doc:document});
 if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',boot,{once:true});
 else boot();
}
